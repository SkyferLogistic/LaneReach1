/**
 * Writes `src/pages/landing/worldDots.ts`: the hero map's land dots as one SVG path.
 *
 * The dots never change, and testing thousands of grid points against the world's land shapes in
 * the browser froze the website for seconds on every visit, so they are computed here once.
 * Run `npm run world-dots` after changing the grid step or the map's projection.
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoContains, geoNaturalEarth1 } from "d3-geo";
import { feature } from "topojson-client";

// Keep in step with WIDTH, HEIGHT and the projection in WorldLanes.tsx.
const WIDTH = 960;
const HEIGHT = 470;
const STEP = 2.4;
const LAT_MIN = -56;
const LAT_MAX = 76;

const require = createRequire(import.meta.url);
const atlas = require("world-atlas/countries-110m.json");
const land = feature(atlas, atlas.objects.land);
const projection = geoNaturalEarth1()
  .scale(178)
  .translate([WIDTH / 2, HEIGHT / 2 + 30]);

const parts = [];
for (let lat = LAT_MAX; lat >= LAT_MIN; lat -= STEP) {
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) {
    if (!geoContains(land, [lon, lat])) continue;
    const xy = projection([lon, lat]);
    if (xy) parts.push(`M${xy[0].toFixed(1)} ${xy[1].toFixed(1)}h0`);
  }
}

const target = new URL("../src/pages/landing/worldDots.ts", import.meta.url);
writeFileSync(
  target,
  `// Generated by scripts/world-dots.mjs (npm run world-dots); do not edit.\n` +
    `/** ${parts.length} land dots of the hero map, as zero-length path segments drawn with round caps. */\n` +
    `export const WORLD_DOTS =\n  "${parts.join("")}";\n`,
);
console.log(`${parts.length} dots written to ${target.pathname}`);
