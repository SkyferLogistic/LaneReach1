"""SQLAlchemy declarative base, shared column mixins and engine construction.

Timestamps are always set by application code from the injected `Clock` (never with
`server_default=now()`), so tests and simulations see consistent time across rows.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import StrEnum
from typing import Any

from sqlalchemy import (
    DateTime,
    Dialect,
    ForeignKey,
    ForeignKeyConstraint,
    MetaData,
    String,
    TypeDecorator,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.ext.asyncio import (
    AsyncEngine,
    AsyncSession,
    async_sessionmaker,
    create_async_engine,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base for every LaneReach table."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map = {
        datetime: DateTime(timezone=True),
        uuid.UUID: UUID(as_uuid=True),
        dict[str, Any]: JSONB,
    }


class StrEnumType[EnumT: StrEnum](TypeDecorator[EnumT]):
    """Stores a `StrEnum` as VARCHAR and loads it back as the enum member.

    A plain `String` column returns `str`, so identity checks such as
    `workflow.status is WorkflowStatus.PUBLISHED` would silently be false.

    Args:
        enum_class: The enum to store.
        length: VARCHAR length.
    """

    impl = String
    cache_ok = True

    def __init__(self, enum_class: type[EnumT], length: int) -> None:
        super().__init__(length)
        self.enum_class = enum_class

    def process_bind_param(self, value: EnumT | str | None, dialect: Dialect) -> str | None:
        """Validate and store the enum's value."""
        return None if value is None else self.enum_class(value).value

    def process_result_value(self, value: str | None, dialect: Dialect) -> EnumT | None:
        """Load the stored value as an enum member."""
        return None if value is None else self.enum_class(value)


class UUIDPrimaryKeyMixin:
    """Adds a random UUID primary key generated by the application."""

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)


class TenantScopedMixin:
    """Adds the `tenant_id` column required on every tenant-owned table.

    Row-Level Security policies (created in migrations with `tenant_rls_statements`) filter
    every query on this column against the `app.tenant_id` session setting.
    """

    tenant_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("tenants.id", ondelete="CASCADE"), index=True
    )


class CreatedAtMixin:
    """Adds a `created_at` timestamp that callers set from the `Clock`."""

    created_at: Mapped[datetime]


def tenant_foreign_key(
    column: str, parent_table: str, *, nullable_column: bool = False
) -> ForeignKeyConstraint:
    """Foreign key on `(tenant_id, column)` → `parent_table (tenant_id, id)`.

    PostgreSQL checks foreign keys without applying RLS, so a plain `column → parent.id` key
    could reference another tenant's row. Including `tenant_id` makes that impossible.

    Args:
        column: The referencing column, for example `company_id`.
        parent_table: The referenced table; it must declare `tenant_unique_id()`.
        nullable_column: When the reference is optional, deleting the parent sets only `column`
            to NULL (PostgreSQL 15+ column list); otherwise children are deleted with it.

    Returns:
        The constraint, for `__table_args__`.
    """
    return ForeignKeyConstraint(
        ["tenant_id", column],
        [f"{parent_table}.tenant_id", f"{parent_table}.id"],
        ondelete=f"SET NULL ({column})" if nullable_column else "CASCADE",
        name=f"fk_tenant_scoped_{column}",
    )


def tenant_unique_id() -> UniqueConstraint:
    """`UNIQUE (tenant_id, id)`, the target of `tenant_foreign_key` constraints.

    Returns:
        The constraint, for `__table_args__`.
    """
    return UniqueConstraint("tenant_id", "id")


def create_engine(url: str, *, pool_size: int = 10, echo: bool = False) -> AsyncEngine:
    """Create an async SQLAlchemy engine.

    Args:
        url: SQLAlchemy URL using the `postgresql+asyncpg` driver.
        pool_size: Connection pool size.
        echo: Log SQL statements (local debugging only).

    Returns:
        A configured `AsyncEngine`. No connection is opened until first use.
    """
    return create_async_engine(url, pool_size=pool_size, pool_pre_ping=True, echo=echo)


def create_session_factory(engine: AsyncEngine) -> async_sessionmaker[AsyncSession]:
    """Create the session factory used for every database session.

    `expire_on_commit=False` keeps loaded attributes usable after commit, which routers need
    to serialize responses after the unit of work has committed.

    Args:
        engine: The engine sessions bind to.

    Returns:
        An `async_sessionmaker` producing `AsyncSession` objects.
    """
    return async_sessionmaker(engine, expire_on_commit=False, autoflush=True)
